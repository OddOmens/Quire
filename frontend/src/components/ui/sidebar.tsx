/** True when the desktop sidebar is collapsed to its rail of icons. */
function useSidebarRail() {
  const { isMobile, state } = useSidebar()
  return !isMobile && state === "collapsed"
}

/**
 * Folds its content away (height to nothing, in step with the sidebar) when
 * the sidebar collapses to icons: sub-trees, hints, anything with no icon to
 * leave behind. `when="rail"` does the opposite, for things only the rail shows.
 */
function SidebarFold({
  when = "open",
  className,
  children,
}: {
  when?: "open" | "rail"
  className?: string
  children: React.ReactNode
}) {
  const rail = useSidebarRail()
  const shown = when === "rail" ? rail : !rail
  return (
    <div
      data-slot="sidebar-fold"
      inert={!shown}
      className={cn(
        "grid transition-[grid-template-rows,opacity]",
        sidebarMotion,
        when === "rail"
          ? "grid-rows-[0fr] opacity-0 group-data-[collapsible=icon]:grid-rows-[1fr] group-data-[collapsible=icon]:opacity-100"
          : "grid-rows-[1fr] group-data-[collapsible=icon]:grid-rows-[0fr] group-data-[collapsible=icon]:opacity-0",
        className
      )}
    >
      <div className="min-h-0 overflow-clip">{children}</div>
    </div>
  )
}

